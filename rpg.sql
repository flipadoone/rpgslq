-- 1. Criar a tabela USUARIOS
CREATE TABLE USUARIOS
(
    UsuarioId INT PRIMARY KEY IDENTITY,
    Email VARCHAR(150) NOT NULL UNIQUE,
    Senha VARCHAR(100) NOT NULL
);
GO

-- 2. Criar a tabela CLASSES
CREATE TABLE CLASSES
(
    ClasseId INT PRIMARY KEY IDENTITY,
    Nome VARCHAR(50) NOT NULL UNIQUE,
    Descricao VARCHAR(255)
);
GO

-- 3. Criar a tabela HABILIDADES
CREATE TABLE HABILIDADES
(
    HabilidadeId INT PRIMARY KEY IDENTITY,
    Nome VARCHAR(100) NOT NULL UNIQUE
);
GO

-- 4. Criar a tabela PERSONAGENS
CREATE TABLE PERSONAGENS
(
    PersonagemId INT PRIMARY KEY IDENTITY,
    NomePersonagem VARCHAR(100) NOT NULL,
    UsuarioId INT FOREIGN KEY REFERENCES USUARIOS (UsuarioId),
    ClasseId INT FOREIGN KEY REFERENCES CLASSES (ClasseId)
);
GO

-- 5. Criar a tabela associativa CLASSES_HABILIDADES
CREATE TABLE CLASSES_HABILIDADES
(
    ClasseId INT FOREIGN KEY REFERENCES CLASSES (ClasseId),
    HabilidadeId INT FOREIGN KEY REFERENCES HABILIDADES (HabilidadeId),
    PRIMARY KEY (ClasseId, HabilidadeId)
);
GO